// `praeko studio skill install [--agent claude|codex|gemini|cursor|opencode|cline|windsurf|all] [--lang en|pt] [--dir folder]`
// Writes Studio's instructions in the format each agent reads. Shared files (AGENTS.md, CLAUDE.md, GEMINI.md) get a delimited block:
// reinstalling updates only the block and keeps the rest of the file.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { BODY, DESCRIPTION, SKILL_NAME } from "./skill-texts.ts";
import type { Lang } from "./skill-texts.ts";
import { lang as outputLang } from "./i18n.ts";

export const BLOCK_START = "<!-- praeko-studio:start (generated by `praeko studio skill install`; edit outside this block) -->", BLOCK_END = "<!-- praeko-studio:end -->";
export const AGENTS = ["claude", "codex", "gemini", "cursor", "opencode", "cline", "windsurf"] as const;
export type Agent = (typeof AGENTS)[number];
const block = (lang: Lang, body: string = BODY[lang]): string => `${BLOCK_START}\n${body}\n${BLOCK_END}\n`;

export type Target = { path: string; kind: "block" | "whole"; content: (lang: Lang) => string };
/** Files of each agent. */
export const TARGETS: Record<Agent, Target[]> = {
  claude: [
    { path: `.claude/skills/${SKILL_NAME}/SKILL.md`, kind: "whole", content: (l) => `---\nname: ${SKILL_NAME}\ndescription: ${DESCRIPTION[l]}\n---\n\n${BODY[l]}` },
    { path: "CLAUDE.md", kind: "block", content: (l) => block(l, l === "en" ? "Video project (Praeko Studio). Full instructions: the `praeko-studio` skill in `.claude/skills/`, or `praeko studio docs`." : "Projeto de vídeo (Praeko Studio). Instruções completas: skill `praeko-studio` em `.claude/skills/`, ou `praeko studio docs`.") },
  ],
  codex: [{ path: "AGENTS.md", kind: "block", content: (l) => block(l) }],
  opencode: [{ path: "AGENTS.md", kind: "block", content: (l) => block(l) }],
  gemini: [{ path: "GEMINI.md", kind: "block", content: (l) => block(l) }],
  cursor: [{ path: `.cursor/rules/${SKILL_NAME}.mdc`, kind: "whole", content: (l) => `---\ndescription: ${DESCRIPTION[l]}\nglobs:\nalwaysApply: true\n---\n\n${BODY[l]}` }],
  cline: [{ path: `.clinerules/${SKILL_NAME}.md`, kind: "whole", content: (l) => BODY[l] }],
  windsurf: [{ path: `.windsurf/rules/${SKILL_NAME}.md`, kind: "whole", content: (l) => `---\ntrigger: always_on\ndescription: ${DESCRIPTION[l]}\n---\n\n${BODY[l]}` }],
};

/** Agents that already left a trace in the folder (default for `init`/`skill install` without --agent). */
export function detectAgents(dir: string): Agent[] {
  const has = (p: string) => existsSync(join(dir, p));
  const r: Agent[] = [];
  if (has(".claude") || has("CLAUDE.md")) r.push("claude");
  if (has("AGENTS.md")) r.push("codex");
  if (has("GEMINI.md")) r.push("gemini");
  if (has(".cursor")) r.push("cursor");
  if (has(".clinerules")) r.push("cline");
  if (has(".windsurf")) r.push("windsurf");
  return r;
}

function write(dir: string, target: Target, lang: Lang): "created" | "updated" {
  const file = join(dir, target.path), fresh = target.content(lang), existed = existsSync(file);
  mkdirSync(dirname(file), { recursive: true });
  if (target.kind === "whole" || !existed) { writeFileSync(file, fresh); return existed ? "updated" : "created"; }
  const current = readFileSync(file, "utf8"), i = current.indexOf(BLOCK_START.slice(0, 26)), j = current.indexOf(BLOCK_END);
  if (i >= 0 && j > i) writeFileSync(file, current.slice(0, i) + fresh.trimEnd() + current.slice(j + BLOCK_END.length));
  else writeFileSync(file, current.replace(/\s*$/, "\n\n") + fresh);
  return "updated";
}

export type Installed = { agent: Agent; file: string; action: "created" | "updated" };
/** Installs. `agents`: list or "all". Returns [{ agent, file, action }] (a shared file is listed once). */
export function installSkill({ dir, agents = "all", lang = "en" }: { dir: string; agents?: readonly string[] | "all"; lang?: string }): Installed[] {
  dir = resolve(dir);
  const list = (agents === "all" ? AGENTS : agents) as readonly string[];
  for (const a of list) if (!(AGENTS as readonly string[]).includes(a)) throw new Error(`unknown agent: ${a} (use ${AGENTS.join(", ")} or all)`);
  if (lang !== "en" && lang !== "pt") throw new Error(`unknown language: ${lang} (en or pt)`);
  const done: Installed[] = [], seen = new Set<string>();
  for (const a of list as Agent[]) for (const t of TARGETS[a]) {
    if (seen.has(t.path)) continue; seen.add(t.path);
    done.push({ agent: a, file: t.path, action: write(dir, t, lang) });
  }
  return done;
}

const flag = (a: string[], k: string): string | undefined => { const i = a.indexOf("--" + k); return i >= 0 ? a[i + 1] : undefined; };
export function skillCommand(a: string[]): number {
  if (a[0] !== "install") throw new Error("usage: praeko studio skill install [--agent claude|codex|gemini|cursor|opencode|cline|windsurf|all] [--lang en|pt] [--dir folder]");
  const dir = resolve(flag(a, "dir") || process.cwd()), ag = flag(a, "agent");
  const agents = ag ? (ag === "all" ? "all" : ag.split(",").map((x) => x.trim())) : (detectAgents(dir).length ? detectAgents(dir) : ["claude", "codex"]);
  const r = installSkill({ dir, agents, lang: flag(a, "lang") || outputLang() });
  for (const x of r) console.log(`✓ ${x.agent.padEnd(9)} ${x.action} ${x.file}`);
  console.log(`\nOpen your agent in this folder (${dir}) and ask for the video. What the agent can do on its own, and what needs your yes, is in the installed text.`);
  return 0;
}
