// Checks what would go to npm (without publishing): tarball contents, exports/bin pointing at files that exist, no test or secret, the bundled CLI working.
import test from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, statSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { listTarball, problems } from "../../../scripts/release-check.mjs";

const root = fileURLToPath(new URL("../../../", import.meta.url));
execFileSync(process.execPath, [root + "scripts/build-cli.mjs"], { stdio: "inherit" });
execFileSync(process.execPath, [root + "scripts/build-studio.mjs"], { stdio: "inherit" });
// The sdk dist is built before the tests (`npm test` and the npm install `prepare`); it is only built here if missing, because rebuilding wipes the dist while other test files import it.
if (!existsSync(root + "packages/sdk/dist/index.js")) execFileSync(process.execPath, [root + "scripts/build-sdk.mjs"], { stdio: "inherit" });

test("sdk tarball: no problems, with the compiled dist (JS + .d.ts generated by tsc) and no source, test, map or tsconfig", () => {
  assert.deepEqual(problems("sdk"), []);
  const { files } = listTarball("packages/sdk");
  for (const m of ["index", "node", "contract", "bridge", "contract-docs", "openapi", "legacy", "types"]) for (const ext of ["js", "d.ts"]) assert.ok(files.includes(`dist/${m}.${ext}`), `dist/${m}.${ext}`);
  assert.ok(!files.some((a) => a.startsWith("test/") || a.startsWith("src/") || /\.(map|ts)$/.test(a) && !a.endsWith(".d.ts") || /tsconfig/.test(a)), "only dist/, README, CHANGELOG, LICENSE and package.json");
  for (const a of files.filter((x) => x.endsWith(".d.ts"))) assert.doesNotMatch(readFileSync(root + "packages/sdk/" + a, "utf8"), /from\s+["']\.\.?\/[^"']*\.ts["']/, `${a}: import relativo com .ts nas declarações`);
});
test("cli tarball: no problems, no monorepo dependencies and with the bundle", () => {
  assert.deepEqual(problems("cli"), []);
  const { files } = listTarball("packages/cli");
  assert.ok(files.includes("dist/praeko.mjs") && !files.includes("dist/arauto.mjs"), "a single bin (praeko): with two, npx @praeko/cli fails");
  assert.ok(!files.some((a) => a.startsWith("src/") || a.startsWith("test/") || a.startsWith("bin/")));
  const pkg = JSON.parse(readFileSync(root + "packages/cli/package.json", "utf8"));
  assert.equal(pkg.dependencies, undefined);
});
test("bundled cli: shebang, execute bit, --version and --help (no network, no Keychain)", () => {
  const bin = root + "packages/cli/dist/praeko.mjs";
  assert.match(readFileSync(bin, "utf8").split("\n")[0], /^#!\/usr\/bin\/env node$/);
  if (process.platform !== "win32") assert.ok(statSync(bin).mode & 0o111, "no execute bit");
  const version = JSON.parse(readFileSync(root + "packages/cli/package.json", "utf8")).version;
  assert.equal(execFileSync(process.execPath, [bin, "--version"], { encoding: "utf8" }).trim(), version);
  assert.match(execFileSync(process.execPath, [bin, "--help"], { encoding: "utf8" }), /Praeko CLI/);
});
test("the Keychain (security command) only turns on on macOS", async () => {
  const { chaveiro } = await import("@praeko/core/segredos").catch(() => import("../../core/src/segredos.ts"));
  const antes = Object.getOwnPropertyDescriptor(process, "platform");
  try { for (const p of ["linux", "win32"]) { Object.defineProperty(process, "platform", { value: p }); assert.equal(chaveiro.ativo(), false); } }
  finally { Object.defineProperty(process, "platform", antes); }
});

test("@praeko/studio tarball: single bin praeko-studio, bundles, docs, templates and LICENSES.md; no source, test, third-party media or legacy alias", () => {
  assert.deepEqual(problems("studio"), []);
  const { files } = listTarball("studio/packages/cli");
  for (const f of ["dist/praeko-studio.mjs", "dist/voice-balance.mjs", "dist/voice-voices.mjs", "dist/voice-account.mjs", "dist/voice-config.mjs", "docs/episode-yaml.md", "docs/long-yaml.md", "docs/publish.md", "docs/voice.md", "docs/hyperframes.md", "templates/avatar.png", "templates/sfx/pop.wav", "LICENSES.md", "LICENSE", "README.md", "CHANGELOG.md"]) assert.ok(files.includes(f), f);
  assert.ok(!files.some((a) => /^(src|test|bin)\//.test(a) || /bardo/i.test(a)), "only dist, docs, templates and metadata");
  const pkg = JSON.parse(readFileSync(root + "studio/packages/cli/package.json", "utf8"));
  assert.deepEqual(Object.keys(pkg.bin), ["praeko-studio"]); assert.deepEqual(Object.keys(pkg.dependencies), ["@elevenlabs/elevenlabs-js"]); assert.equal(pkg.engines.node, ">=22");
  for (const peerless of ["remotion", "react"]) assert.equal(pkg.dependencies[peerless], undefined, "Studio does not pull Remotion: it lives in the user's project");
});
test("@praeko/studio-core and @praeko/studio-kit tarballs: dist with .d.ts, remotion/react peers, no src or tests", () => {
  for (const [key, dir] of [["studio-core", "studio/packages/core"], ["studio-kit", "studio/packages/kit"]]) {
    assert.deepEqual(problems(key), []);
    const { files } = listTarball(dir), pkg = JSON.parse(readFileSync(root + dir + "/package.json", "utf8"));
    for (const f of ["dist/index.js", "dist/index.d.ts", "LICENSES.md", "LICENSE"]) assert.ok(files.includes(f), `${key}: ${f}`);
    assert.ok(!files.some((a) => a.startsWith("src/") || a.startsWith("test/")));
    assert.match(pkg.peerDependencies.remotion, /^\^4\./); assert.match(pkg.peerDependencies.react, /^\^19/); assert.equal(pkg.dependencies, undefined);
    assert.equal(pkg.license, "MIT"); assert.equal(pkg.publishConfig.access, "public"); assert.equal(pkg.version, "0.2.0");
  }
  assert.equal(JSON.parse(readFileSync(root + "studio/packages/kit/package.json", "utf8")).peerDependencies["@praeko/studio-core"], "^0.2.0");
});
test("packed @praeko/studio: --version, help and doctor run from dist, without network or keychain", () => {
  const bin = root + "studio/packages/cli/dist/praeko-studio.mjs", env = { ...process.env, PRAEKO_NO_KEYCHAIN: "1", HOME: root + "studio/packages/cli/dist" };
  assert.equal(execFileSync(process.execPath, [bin, "--version"], { encoding: "utf8", env }).trim(), JSON.parse(readFileSync(root + "studio/packages/cli/package.json", "utf8")).version);
  assert.match(execFileSync(process.execPath, [bin, "--help"], { encoding: "utf8", env }), /doctor/);
});
